create_bins_app = typer.Typer()


def _iter_media_files(input_folder: Path, recursive: bool):
    if recursive:
        for root, _, files in os.walk(input_folder):
            root_path = Path(root)
            for file_name in files:
                file_path = (root_path / file_name).resolve()
                if file_path.suffix.lower() in SUPPORTED_EXTENSIONS:
                    yield file_path
        return

    with os.scandir(input_folder) as entries:
        for entry in entries:
            if not entry.is_file():
                continue
            file_path = Path(entry.path).resolve()
            if file_path.suffix.lower() in SUPPORTED_EXTENSIONS:
                yield file_path

def _load_timeline_blocks() -> tuple[str, str]:
    timelines_content = read_lua_file("timelines.lua")
    split_marker = "-- @@AGGREGATE@@"
    if split_marker not in timelines_content:
        raise RuntimeError("lua_shared/timelines.lua is missing the aggregate split marker")
    per_bin_block, aggregate_block = timelines_content.split(split_marker, maxsplit=1)
    return per_bin_block.strip("\n"), aggregate_block.strip("\n")


def render_lua(
    output_path: Path,
    source_folder: Path,
    release_name: ReleaseName,
    clip_bin_groups: list[ClipBinGroup],
    timelines: bool
) -> str:

    def _bin_name(kind: str, layer: int) -> str:
        suffix = chr(ord("A") + layer - 1)
        return f"{release_name.parent_text()}_{kind}_{suffix}"

    lines = [
        "-- Generated by create_bins_lua.py",
        "-- Paste into the DaVinci Resolve Lua console to run this file:",
        f"-- dofile([[{output_path.resolve()}]])",
        f"-- Source folder: {source_folder}",
        f"-- Generated at: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}",
        "",
        f"CREATE_TIMELINES = {'true' if timelines else 'false'}",
        f"SCENERULES_SEP = {lua_string(SCENE_NAME_SEP)}",
        f"SOURCE_FOLDER = {lua_string(str(source_folder))}",
        f"PARENT_BIN_NAME = {lua_string(release_name.parent_text())}",
        "BINS = {",
    ]

    for clips_bin in tqdm(clip_bin_groups, position=0):
        lines.extend(
            [
                "    {",
                f"        name = {lua_string(_bin_name(clips_bin.kind, clips_bin.layer))},",
                f"        release_name = {lua_string(clips_bin.release_name)},",
                # or release name components (in rendering order):
                f"        parent = {lua_string(clips_bin.parent)},",
                f"        date = {lua_string(clips_bin.date)},",
                f"        title = {lua_string(clips_bin.title)},",
                f"        section = {lua_string(clips_bin.section)},",
                f"        tags = {lua_list(clips_bin.tags)},",
                f"        group = {lua_string(clips_bin.group)},",
                # bin info
                f"        kind = {lua_string(clips_bin.kind)},",
                f"        layer = {clips_bin.layer},",
                f"        totalFrames = {clips_bin.total_frames},",
                # clips
                "        clips = {",
            ]
        )
        for clip in tqdm(clips_bin.clips, leave=False, position=1):
            lines.extend(
                [
                    "            {",
                    f"                path = {lua_string(str(clip.path))},",
                    # TODO: replace this todo with 3 todo items to add useful clip meta fields
                    f"                frames = {clip.frames},",
                    "            },",
                ]
            )
        lines.extend(["        },", "    },"])

    lines.extend(["}", ""])

    bins_template = read_lua_file("bins.lua")
    per_bin_timeline_block, aggregate_timeline_block = _load_timeline_blocks()
    bins_script = bins_template.replace("-- @@PER_BIN_TIMELINES@@", per_bin_timeline_block)
    bins_script = bins_script.replace("-- @@AGGREGATE_TIMELINES@@", aggregate_timeline_block)
    lines.extend(bins_script.splitlines())

    lines.extend(
        [
            "",
            "media_pool:SetCurrentTimeline(original_timeline)",
            "media_pool:SetCurrentFolder(parent_folder)",
            "",
        ]
    )

    return "\n".join(lines)



@create_bins_app.command()
def create_bins(
    input_folder: Path = typer.Argument(..., exists=True, dir_okay=True, file_okay=False, resolve_path=True),
    name: str = typer.Option(..., "--name"),
    section: str | None = typer.Option(None, "--section"),
    group_name: str | None = typer.Option(None, "--group"),
    tag: list[str] = typer.Option([], "--tag"),
    date_format: DateFormatTyperOption = typer.Option(DateFormatTyperOption.long, '--date', show_default=True),
    recursive: bool = typer.Option(True, "--recursive", metavar="FLAG"),
    copy: bool = typer.Option(False, "--copy", metavar="FLAG"),
    only_bins: bool = typer.Option(False, "--only-bins", metavar="FLAG", show_default=True),
):
    input_folder = input_folder.expanduser().resolve()
    if not input_folder.exists() or not input_folder.is_dir():
        raise RuntimeError(f"Input folder does not exist or is not a directory: {input_folder}")

    ffprobe_path = shutil.which("ffprobe")
    if not ffprobe_path:
        raise RuntimeError(f"ffprobe not found: {ffprobe_path}")

    clips: list[ClipDataInput] = []
    media_file_count = 0
    for media_file in tqdm(_iter_media_files(input_folder, recursive), desc="scan+ffprobe", unit="clip", position=0):
        media_file_count += 1
        result = subprocess.run(
            [
                ffprobe_path,
                "-v",
                "error",
                "-show_entries",
                "stream=codec_type,codec_name,width,height,nb_frames,avg_frame_rate,r_frame_rate,duration:format=duration",
                "-of",
                "json",
                str(media_file),
            ],
            capture_output=True,
            text=True,
            check=False,
        )
        if result.returncode != 0:
            continue

        file_stat = media_file.stat()
        file_size = file_stat.st_size
        file_ext = media_file.suffix.lower()
        file_birth_ts = getattr(file_stat, "st_birthtime", file_stat.st_birthtime)
        file_birth_date = datetime.fromtimestamp(file_birth_ts).isoformat(timespec="seconds")

        try:
            payload = json.loads(result.stdout)
            streams = payload.get("streams") or []
            video_stream = next((item for item in streams if item.get("codec_type") == "video"), None)
            if video_stream is None:
                raise ValueError("missing video stream")
            audio_stream = next((item for item in streams if item.get("codec_type") == "audio"), None)

            width = int(video_stream.get("width") or 0)
            height = int(video_stream.get("height") or 0)
            fps_text = video_stream.get("avg_frame_rate") or video_stream.get("r_frame_rate") or "0/0"
            fps = float(Fraction(str(fps_text))) if fps_text not in {"0/0", "", "0"} else 0.0
            frames_text = str(video_stream.get("nb_frames") or "").strip()
            frames = int(frames_text) if frames_text.isdigit() else 0
            duration = float(video_stream.get("duration") or (payload.get("format") or {}).get("duration") or 0)
            video_codec = str(video_stream.get("codec_name") or "unknown")
            audio_codec = str(audio_stream.get("codec_name") or "noaudio") if audio_stream else "noaudio"
            if not frames:
                frames = round(float(duration) * fps) if fps and duration else 0
            if frames <= 0:
                raise ValueError("missing usable frame metadata")
        except Exception:
            continue

        clips.append(
            ClipDataInput(
                path=media_file,
                frames=frames,
                fps=fps,
                video_codec=video_codec,
                audio_codec=audio_codec,
                width=width,
                height=height,
                kind="Vertical" if height > width else "Full",
                file_size=file_size,
                file_ext=file_ext,
                file_created=file_birth_date,
            )
        )

    if media_file_count == 0:
        raise RuntimeError(f"No supported media files found in {input_folder}")

    release_name = ReleaseName()
    release_name.addRoleValue(NameTag.Role.Name, name)
    if date_format == DateFormatTyperOption.long:
        release_name.addRoleValue(NameTag.Role.LongDate, True)
    elif date_format == DateFormatTyperOption.short:
        release_name.addRoleValue(NameTag.Role.ShortDate, True)
    for item in tag:
        release_name.addRoleValue(NameTag.Role.Tag, item)
    release_name.addRoleValue(NameTag.Role.Section, section)
    release_name.addRoleValue(NameTag.Role.Group, group_name)
    output_bins = organize_bins(clips, release_name, 3)
    output_path = PROCESSED_DATA_DIR / "create_bins" / release_name.file_name()
    output_path.parent.mkdir(parents=True, exist_ok=True)

    output_path.write_text(
        render_lua(output_path, input_folder, release_name, output_bins, not only_bins),
        encoding="utf-8",
        newline="\n",
    )

    typer.echo(f"Wrote Lua script: {output_path}")

    logger.success(f"Wrote Lua script: {output_path}")
    typer.echo(luautil.lua_dofile_hint(output_path, copy))
